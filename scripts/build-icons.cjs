const fs = require('node:fs');
const path = require('node:path');
const { root, registry, readLibrary } = require('./icon-library.cjs');
function artifacts() {
  const manifest = readLibrary();
  const situations = registry();
  const icons = Object.fromEntries(manifest.icons.map((entry) => [entry.alias, { ...entry,
    svg: fs.readFileSync(path.join(root, 'icons', entry.file), 'utf8') }]));
  const approved = '/* Generated by scripts/build-icons.cjs. */\nwindow.DesignSystemApprovedIcons = ' + JSON.stringify({ version: manifest.version, icons }) + ';\n';
  const files = [
    { name: 'icons/manifest.json', content: JSON.stringify({ ...manifest, situations: situations.map((icon) => ({ alias: icon.alias, name: icon.name,
      category: icon.category, usage: icon.notes || '', apps: icon.apps || [], status: icons[icon.alias] ? 'approved' : 'needs-icon' })) }, null, 2) + '\n' },
    { name: 'js/icon-approved.js', content: approved },
    { name: 'js/icon-runtime.js', content: fs.readFileSync(path.join(root, 'js/icon-runtime.js'), 'utf8') },
    { name: 'icons/README.md', content: '# Approved semantic icons\n\nLoad js/icon-approved.js then js/icon-runtime.js. Use <span data-ds-icon="action.search"></span> inside a button with visible text or an aria-label. Icons are decorative; label the control. Call DesignSystemIcons.render(container) after adding content. Unknown aliases are empty and marked data-ds-icon-state="missing". Individual SVGs and the manifest are included for other frameworks. No network request is required. Only approved assets ship; candidate selections and browser defaults do not. Keep licenses with copied assets.\n' },
    ...manifest.icons.map((entry) => ({ name: 'icons/' + entry.file, content: icons[entry.alias].svg })),
    ...manifest.icons.map((entry) => ({ name: 'icons/licenses/' + entry.alias + '.txt', content: entry.source.licenseText + '\n' })),
  ];
  return { 'js/icon-approved.js': approved,
    'js/icon-package-assets.js': '/* Generated approved icon export files. */\nwindow.DesignSystemIconPackageAssets = ' + JSON.stringify({ version: manifest.version, files }) + ';\n' };
}
function build(check = false) {
  for (const [file, content] of Object.entries(artifacts())) {
    const target = path.join(root, file);
    if (check) { if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) throw new Error('Stale icon artifact: ' + file); }
    else fs.writeFileSync(target, content);
  }
  console.log(check ? 'Approved icon artifacts are current.' : 'Built approved icon registry and package assets.');
}
function reconcilePackage(destination, files) {
  const directory = path.resolve(destination, 'design-system/icons/approved');
  if (!directory.startsWith(path.resolve(destination) + path.sep)) throw new Error('Invalid generated asset directory');
  if (!fs.existsSync(directory)) return;
  const expected = new Set(files.map((file) => file.name));
  for (const name of fs.readdirSync(directory)) {
    if (/^[a-z0-9.-]+-[a-f0-9]{16}\.svg$/.test(name) && !expected.has('design-system/icons/approved/' + name)) fs.unlinkSync(path.join(directory, name));
  }
}
if (require.main === module) build(process.argv.includes('--check'));
module.exports = { build, artifacts, reconcilePackage };
